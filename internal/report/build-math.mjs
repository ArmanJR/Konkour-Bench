// Rebuild with `make report-assets` after installing dashboard dependencies.
import { readFile, writeFile } from "node:fs/promises";

const here = new URL("./", import.meta.url);
const dist = new URL("../../dashboard/node_modules/katex/dist/", here);
const [core, auto, css, license] = await Promise.all(
  [
    "katex.min.js",
    "contrib/auto-render.min.js",
    "katex.min.css",
    "../LICENSE",
  ].map((path) => readFile(new URL(path, dist), "utf8")),
);
let embedded = css;
// src is often the final declaration, with no trailing semicolon. Never
// consume the closing brace or the following font-face rule.
const sources = [...css.matchAll(/src:([^;}]+)/g)];
for (const [rule, value] of sources) {
  const font = value.match(/url\(([^)]+\.woff2)\)/);
  if (!font) throw new Error(`Missing WOFF2 source in ${rule}`);
  const bytes = await readFile(new URL(font[1], dist));
  embedded = embedded.replace(
    rule,
    `src:url(data:font/woff2;base64,${bytes.toString("base64")}) format('woff2')`,
  );
}
await writeFile(
  new URL("math.generated.js", here),
  `/* Generated by build-math.mjs. KaTeX license:\n${license}\n*/\n${core}\n${auto}\n`,
);
await writeFile(
  new URL("math.generated.css", here),
  `/* Generated by build-math.mjs from KaTeX. */\n${embedded.trimEnd()}\n`,
);
